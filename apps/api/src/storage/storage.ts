import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';

export interface UploadTarget {
  readonly url: string;
  readonly method: 'PUT';
  readonly headers: Readonly<Record<string, string>>;
  readonly expiresAt: Date;
}

export interface UploadRequest {
  readonly contentType: string;
  readonly maxBytes: number;
  readonly expiresInSeconds: number;
}

/**
 * Private file storage (PRD FR-128): files are uploaded straight to storage through short-lived
 * signed URLs and never have public URLs. Production uses S3 in ap-south-1 with SSE-KMS; the
 * local adapter is for development and tests only (refused in production by configuration).
 */
export interface StorageProvider {
  readonly name: string;
  createUploadTarget(key: string, request: UploadRequest): Promise<UploadTarget>;
  /** Server-side write (generated files such as exports). */
  write(key: string, data: Buffer): Promise<void>;
  read(key: string): Promise<Buffer>;
  size(key: string): Promise<number | null>;
  delete(key: string): Promise<void>;
}

export const STORAGE_PROVIDER = Symbol('STORAGE_PROVIDER');

/** Storage keys are generated by Nivomi, never taken from a user's file name. */
const SAFE_KEY = /^[a-z0-9-]+(\/[a-z0-9-]+)*(\.[a-z0-9]+)?$/;

export function assertSafeKey(key: string): void {
  if (!SAFE_KEY.test(key)) throw new Error(`Unsafe storage key: ${key}`);
}

export class LocalStorageProvider implements StorageProvider {
  readonly name = 'local';
  private readonly root: string;

  constructor(
    directory: string,
    /** Builds the signed URL the browser uploads to (served by UploadsController). */
    private readonly uploadUrl: (key: string, request: UploadRequest) => string,
  ) {
    this.root = resolve(directory);
  }

  createUploadTarget(key: string, request: UploadRequest): Promise<UploadTarget> {
    assertSafeKey(key);
    return Promise.resolve({
      url: this.uploadUrl(key, request),
      method: 'PUT',
      headers: { 'Content-Type': request.contentType },
      expiresAt: new Date(Date.now() + request.expiresInSeconds * 1000),
    });
  }

  /** Used by the upload endpoint after it verified the signed token, and by export jobs. */
  async write(key: string, data: Buffer): Promise<void> {
    const path = this.path(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, data);
  }

  read(key: string): Promise<Buffer> {
    return readFile(this.path(key));
  }

  async size(key: string): Promise<number | null> {
    try {
      return (await stat(this.path(key))).size;
    } catch {
      return null;
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.path(key), { force: true });
  }

  private path(key: string): string {
    assertSafeKey(key);
    const path = resolve(join(this.root, key));
    if (!path.startsWith(this.root + sep)) throw new Error('Storage key escapes the root');
    return path;
  }
}
